-- Штрихкоды номенклатуры массивом.
--
-- У растения их несколько сразу: два EAN13 с этикетки и код, выданный
-- маркетплейсом, вида OZN1851256804. Последний и есть единственное, что
-- совпадает у СБИС и у площадки: код товара и артикул у них свои. Раньше
-- обмен просил поле barcode в единственном числе — такого поля СБИС не
-- отдаёт вовсе, и до магазина не доезжал ни один код.
--
-- Держим массивом на самой номенклатуре, а не отдельной таблицей: коды
-- живут и умирают вместе с позицией, отдельной жизни у них нет.
ALTER TABLE saby_nomenclature
  ADD COLUMN IF NOT EXISTS barcodes TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];

CREATE INDEX IF NOT EXISTS saby_nomenclature_barcodes_idx
  ON saby_nomenclature USING GIN (barcodes);
