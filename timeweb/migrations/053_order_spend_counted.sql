-- Отметка, что выполненный заказ уже учтён в персональной скидке.
--
-- Кабинет обещает покупателю, что скидка растёт после выполненных
-- заказов. До сих пор не росло ничего: lifetime_spend_minor не увеличивался
-- ни разу за всю историю магазина.
--
-- Колонка нужна не для самого подсчёта — сумма всегда считается заново по
-- всем выполненным заказам — а чтобы найти, у кого скидку пора
-- пересчитать: без отметки пришлось бы каждую минуту пересчитывать всю
-- базу покупателей.
--
-- У уже выполненных заказов отметка остаётся пустой нарочно: их надо
-- учесть первым же проходом, иначе постоянные покупатели останутся без
-- заработанной скидки.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS spend_counted_at TIMESTAMPTZ;
