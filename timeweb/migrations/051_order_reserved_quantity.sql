-- Сколько штук заказ реально снял со склада.
--
-- Резерв и количество в заказе — разные числа. Когда товара не хватает,
-- строка становится предзаказом: покупатель просит пять, свободно три —
-- резервируем три, а в order_items.quantity лежит пять. Возврат резерва
-- при отмене считал по quantity и возвращал пять, забирая две штуки из
-- чужих резервов. Если свободного не было вовсе, резервировался ноль, а
-- возвращалось всё количество — прямой путь к пересорту.
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS reserved_qty INTEGER NOT NULL DEFAULT 0;

-- Для уже существующих строк точное число восстановить неоткуда. Обычная
-- строка (не предзаказ) резервировалась целиком — берём quantity. У
-- предзаказа резерв был меньше количества и неизвестен: ставим ноль.
-- Недовозврат оставит товар в резерве, и это заметит менеджер; перевозврат
-- продал бы одно растение дважды.
UPDATE order_items
SET reserved_qty = CASE WHEN is_preorder = 0 THEN quantity ELSE 0 END
WHERE reserved_qty = 0;
