-- Две таблицы пережили механизмы, которые их создали.
--
-- integration_credentials — хранилище ключей интеграций с RSA-шифрованием.
-- Ключа расшифровки в Timeweb не оказалось, из-за этого молча отвалились
-- сначала Telegram, потом СДЭК. 5 августа 2026 механизм удалён целиком
-- вместе с утилитой seedcredential; все ключи живут в окружении. Содержимое
-- таблицы нечитаемо в принципе.
--
-- otp_codes — коды подтверждения со времён входа по паролю и СМС.
-- Сейчас вход по звонку, состояние проверки лежит в call_checks.
--
-- Сверено с живой базой: обе таблицы там есть, статистика по ним не
-- собиралась ни разу — их никогда не писали. Ни один запрос в коде их не
-- упоминает.
--
-- Без CASCADE намеренно: если на таблицу вдруг кто-то ссылается, миграция
-- упадёт и это будет видно, а не удалит зависимость молча.
--
-- В той же базе лежат content_bot_state и content_publication_claims —
-- это Ficusin Content Bot, чужой сервис. Миграции магазина его таблицы
-- не трогают.

DROP TABLE IF EXISTS integration_credentials;
DROP TABLE IF EXISTS otp_codes;
