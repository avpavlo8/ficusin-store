import {expect,test} from '@playwright/test';
import {mockApi,owner,horizontalOverflow} from './helpers';
test('@desktop @phone marketplace menu opens isolated channels and preserves history',async({page},testInfo)=>{
 await mockApi(page,owner);
 await page.route('**/api/v1/admin/dashboard',r=>r.fulfill({json:{user:{fullName:'Александр'},role:'owner',permissions:['dashboard.read','products.read','integrations.edit'],dashboard:{}}}));
 await page.route('**/api/v1/admin/flowwow',r=>r.fulfill({json:{configured:true,publicationMode:'mock',shopId:'1',items:[]}}));
 await page.route('**/api/v1/admin/procurement',r=>r.fulfill({json:{integrationHealth:[{channel:'wb',configured:true},{channel:'ozon',configured:true},{channel:'saby',configured:false}],integrationSync:[{channel:'wb',resource:'catalog',status:'ok'},{channel:'ozon',resource:'catalog',status:'error',lastError:'Ошибка Ozon для проверки фильтра'}]}}));
 await page.route('**/api/v1/admin/avito',r=>r.fulfill({json:{items:[],state:{configured:false,publicationEnabled:false,feedUrl:'',lastError:''}}}));
 const writes:string[]=[];page.on('request',r=>{if(!['GET','HEAD'].includes(r.method()))writes.push(r.url())});
 await page.goto('/admin?section=marketplaces&channel=flowwow');
 const nav=page.getByRole('navigation',{name:'Маркетплейсы',exact:true});
 await expect(nav.getByRole('link')).toHaveText(['Flowwow','Wildberries','Ozon','Авито','Обзор обмена']);
 await expect(nav.getByRole('link',{name:'Flowwow',exact:true})).toHaveAttribute('aria-current','page');
 await expect(page.getByRole('heading',{name:'Flowwow',exact:true})).toBeVisible();
 const nb=await nav.boundingBox(),cb=await page.locator('.marketplace-channel-content').boundingBox();
 if((page.viewportSize()?.width||0)>900)expect(nb!.x+nb!.width).toBeLessThanOrEqual(cb!.x);else expect(nb!.y+nb!.height).toBeLessThanOrEqual(cb!.y);
 await page.screenshot({path:testInfo.outputPath('marketplace-side-menu.png'),fullPage:true});
 await nav.getByRole('link',{name:'Wildberries',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Wildberries',exact:true})).toBeVisible();
 await expect(page.getByText('Ошибка Ozon для проверки фильтра',{exact:true})).toHaveCount(0);
 await expect(page.locator('.integration-channel-grid article')).toHaveCount(1);
 await nav.getByRole('link',{name:'Ozon',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Ozon',exact:true})).toBeVisible();
 await page.getByText('Подробнее',{exact:true}).click();
 await expect(page.getByText('Ошибка Ozon для проверки фильтра',{exact:true})).toBeVisible();
 await nav.getByRole('link',{name:'Авито',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Авито',exact:true})).toBeVisible();
 await page.goBack();await expect(nav.getByRole('link',{name:'Ozon',exact:true})).toHaveAttribute('aria-current','page');
 await page.reload();await expect(page.getByRole('heading',{name:'Ozon',exact:true})).toBeVisible();
 expect(writes).toEqual([]);expect(await horizontalOverflow(page)).toBeLessThanOrEqual(1);
 await page.goto('/admin?section=avito&product=210&q=Наташа');
 await expect(page).toHaveURL(/section=marketplaces&product=210&q=.*&channel=avito/);
 await expect(nav.getByRole('link',{name:'Авито',exact:true})).toHaveAttribute('aria-current','page');
});
