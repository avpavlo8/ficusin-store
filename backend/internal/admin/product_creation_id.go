package admin

// Browser drafts use UUID v4 keys. The key is scoped to the authenticated
// actor, never a product ID or an authority to read another actor's receipt.
func validProductCreationID(value string) bool {
	if len(value) != 36 {
		return false
	}
	for i, ch := range value {
		if i == 8 || i == 13 || i == 18 || i == 23 {
			if ch != '-' {
				return false
			}
			continue
		}
		if !(ch >= '0' && ch <= '9' || ch >= 'a' && ch <= 'f') {
			return false
		}
	}
	return true
}
