"""Compile the owner-reviewed input into an atomic, identity-guarded migration."""
import json
from pathlib import Path

root=Path(__file__).resolve().parents[1]
source=root/'docs/agreed-plant-measurements-2026-10-31.json'
rows=json.loads(source.read_text())
assert len(rows)==len({r['sku'] for r in rows})==249
payload=json.dumps(rows,ensure_ascii=False,separators=(',',':'))
template=r'''-- Generated by scripts/generate_agreed_measurements.py. Owner-approved 31 October 2026.
-- Input: docs/agreed-plant-measurements-2026-10-31.json (17 sheets, 249 sizes).
-- SKU 722 was crossed out. Prices, stock, publication and the selected season are untouched.
-- Each existing value/source/timestamp and the old label are retained in admin_audit_log.
INSERT INTO attribute_definitions(code,name,data_type,unit,audience,value_scope,is_global,is_active,description)
VALUES('pot_width_cm','Ширина горшка','number','см','customer','variant',FALSE,TRUE,
       'Ширина некруглой ёмкости; не является диаметром')
ON CONFLICT(code) DO NOTHING;

INSERT INTO category_attributes(category_id,attribute_id,is_required,is_filterable,show_on_pdp,is_badge,sort_order,show_in_summary,summary_position,show_in_characteristics,is_excluded)
SELECT ca.category_id,width.id,FALSE,FALSE,ca.show_on_pdp,FALSE,ca.sort_order+1,FALSE,NULL,ca.show_in_characteristics,ca.is_excluded
FROM category_attributes ca
JOIN attribute_definitions diameter ON diameter.id=ca.attribute_id AND diameter.code='pot_diameter_cm'
CROSS JOIN attribute_definitions width
WHERE width.code='pot_width_cm'
ON CONFLICT(category_id,attribute_id) DO NOTHING;

DO $import$
DECLARE
  input jsonb := $measurements$__PAYLOAD__$measurements$::jsonb;
  matched integer;
  already_applied integer;
  item record;
BEGIN
  SELECT count(*) INTO already_applied FROM admin_audit_log
  WHERE action='variant.measurements.import.20261031';
  IF already_applied=249 THEN RETURN; END IF;
  IF already_applied<>0 THEN RAISE EXCEPTION 'Incomplete measurement audit: %',already_applied; END IF;

  CREATE TEMP TABLE agreed_measurement_input ON COMMIT DROP AS
  SELECT * FROM jsonb_to_recordset(input) AS x(
    sku text,variant_id bigint,product_code bigint,expected_name text,
    expected_label text,label text,page integer,attributes jsonb);
  ALTER TABLE agreed_measurement_input ADD PRIMARY KEY(sku);

  -- Lock the exact, fresh public-catalogue identities before snapshotting any values.
  PERFORM v.id FROM agreed_measurement_input x
  JOIN product_variants v ON v.id=x.variant_id AND v.sku=x.sku
  JOIN products p ON p.id=v.product_id AND p.product_code=x.product_code
  WHERE p.name=x.expected_name AND v.label=x.expected_label
    AND p.catalog_section='plants' AND p.status='published'
    AND v.is_active=1 AND v.archived_at IS NULL
  FOR UPDATE OF v,p;
  GET DIAGNOSTICS matched=ROW_COUNT;
  -- A fresh installation does not contain this owner's live catalogue.
  IF matched=0 THEN
    RAISE NOTICE 'Measurement import: no matching live catalogue; no values changed';
    RETURN;
  END IF;
  IF matched<>249 THEN
    RAISE EXCEPTION 'Measurement identities changed: matched % of 249; no values changed',matched;
  END IF;

  IF EXISTS(SELECT 1 FROM agreed_measurement_input x CROSS JOIN LATERAL jsonb_each(x.attributes) a
    LEFT JOIN attribute_definitions d ON d.code=a.key AND d.value_scope='variant' AND d.is_active
    WHERE d.id IS NULL OR d.data_type<>'number'
      OR a.value<>'null'::jsonb AND (jsonb_typeof(a.value)<>'number' OR (a.value#>>'{}')::numeric<=0)) THEN
    RAISE EXCEPTION 'Invalid measurement value or attribute definition';
  END IF;

  INSERT INTO admin_audit_log(actor_role,action,entity_type,entity_id,before_data,after_data)
  SELECT 'owner','variant.measurements.import.20261031','variant',v.id::text,
    jsonb_build_object('label',v.label,'unchangedVariant',to_jsonb(v)-'label'-'updated_at',
      'attributes',COALESCE((SELECT jsonb_object_agg(d.code,jsonb_build_object(
        'value',a.value,'source',a.source,'updatedAt',a.updated_at))
        FROM variant_attribute_values a JOIN attribute_definitions d ON d.id=a.attribute_id
        WHERE a.variant_id=v.id AND x.attributes ? d.code),'{}'::jsonb)),
    jsonb_build_object('sku',x.sku,'sourcePage',x.page,'label',x.label,'attributes',x.attributes)
  FROM agreed_measurement_input x JOIN product_variants v ON v.id=x.variant_id;

  DELETE FROM variant_attribute_values a USING agreed_measurement_input x,attribute_definitions d
  WHERE a.variant_id=x.variant_id AND a.attribute_id=d.id AND x.attributes->d.code='null'::jsonb;
  INSERT INTO variant_attribute_values(variant_id,attribute_id,value,source,updated_at)
  SELECT x.variant_id,d.id,a.value,'local',CURRENT_TIMESTAMP
  FROM agreed_measurement_input x CROSS JOIN LATERAL jsonb_each(x.attributes) a
  JOIN attribute_definitions d ON d.code=a.key
  WHERE a.value<>'null'::jsonb
  ON CONFLICT(variant_id,attribute_id) DO UPDATE
    SET value=EXCLUDED.value,source=EXCLUDED.source,updated_at=EXCLUDED.updated_at;

  UPDATE product_variants v SET label=x.label,updated_at=CURRENT_TIMESTAMP
  FROM agreed_measurement_input x WHERE v.id=x.variant_id;

  -- Re-read every field in the same transaction; any error rolls back the whole batch.
  IF EXISTS(SELECT 1 FROM agreed_measurement_input x CROSS JOIN LATERAL jsonb_each(x.attributes) a
    JOIN attribute_definitions d ON d.code=a.key
    LEFT JOIN variant_attribute_values saved ON saved.variant_id=x.variant_id AND saved.attribute_id=d.id
    WHERE COALESCE(saved.value,'null'::jsonb) IS DISTINCT FROM a.value) THEN
    RAISE EXCEPTION 'Measurement import verification failed';
  END IF;
  IF EXISTS(SELECT 1 FROM agreed_measurement_input x JOIN product_variants v ON v.id=x.variant_id
    JOIN admin_audit_log audit ON audit.entity_id=v.id::text AND audit.action='variant.measurements.import.20261031'
    WHERE v.label<>x.label OR to_jsonb(v)-'label'-'updated_at' IS DISTINCT FROM audit.before_data->'unchangedVariant') THEN
    RAISE EXCEPTION 'Measurement import changed an unrelated variant field';
  END IF;
  RAISE NOTICE 'Measurement import: 249 sizes, 2239 numeric values verified, 3 non-diameter values cleared; season preserved';
END;
$import$;
'''
(root/'timeweb/migrations/20261031_agreed_plant_measurements.sql').write_text(template.replace('__PAYLOAD__',payload))
